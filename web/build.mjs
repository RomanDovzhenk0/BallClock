// npm run build: src/ → dist/site.html (one page, CSS and JS inline) → ../firmware/src/site_page.h (gzip in PROGMEM).
// No dependencies: the modules are joined in import order into one strict scope (their top-level names are unique),
// comments and indentation are dropped, and the gzip is deterministic (no name, mtime 0, OS byte fixed).
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { constants, gzipSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "src");
const LIMIT = 64 * 1024;

const IMPORT = /^import\s*\{[^}]*\}\s*from\s*"\.\/([\w.]+)";\s*$/gm;

// the modules from app.js, each after the ones it imports
function order(entry) {
    const out = [], seen = new Set();
    const visit = (name) => {
        if (seen.has(name)) return;
        seen.add(name);
        const text = readFileSync(join(src, name), "utf8").replace(/\r\n/g, "\n");
        for (const m of text.matchAll(IMPORT)) visit(m[1]);
        out.push({ name, text });
    };
    visit(entry);
    return out;
}

// whole-line comments and indentation out; strings never span lines in src/, so this is safe
function squeeze(js) {
    return js
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l && !l.startsWith("//"))
        .join("\n");
}

export function bundle() {
    const mods = order("app.js");
    const names = new Map();
    const parts = mods.map(({ name, text }) => {
        let js = text.replace(IMPORT, "").replace(/^export\s*\{[^}]*\};\s*$/gm, "").replace(/^export\s+(?=(const|let|function|class|async)\b)/gm, "");
        if (/^\s*(import|export)\b/m.test(js)) throw new Error(name + ": an import or export the build cannot join");
        for (const m of js.matchAll(/^(?:const|let|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm)) {
            if (names.has(m[1])) throw new Error(m[1] + " is declared in " + names.get(m[1]) + " and " + name);
            names.set(m[1], name);
        }
        return "// " + name + "\n" + js;
    });
    const js = '(()=>{"use strict";\n' + squeeze(parts.join("\n")) + "\n})();";
    new Function(js);  // throws on a syntax error
    const css = readFileSync(join(src, "style.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "").split(/\r?\n/).map((l) => l.trim()).filter(Boolean).join("\n");
    const page = readFileSync(join(src, "page.html"), "utf8").replace(/\r\n/g, "\n");
    if (js.includes("</script")) throw new Error("the script holds </script");
    return page.replace("/*CSS*/", () => css).replace("/*JS*/", () => js);
}

export function gzip(buf) {
    const gz = gzipSync(buf, { level: constants.Z_BEST_COMPRESSION, memLevel: 9, strategy: constants.Z_DEFAULT_STRATEGY });
    gz.writeUInt32LE(0, 4);  // mtime
    gz[9] = 3;  // OS: the same byte on every machine
    return gz;
}

export function header(gz) {
    const etag = createHash("sha256").update(gz).digest("hex").slice(0, 16);
    const rows = [];
    for (let i = 0; i < gz.length; i += 16) rows.push("    " + [...gz.subarray(i, i + 16)].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
    return [
        "#pragma once",
        "// The clock's site (BallClock/web), gzipped. Generated by web/build.mjs (npm run build): do not edit.",
        "#include <Arduino.h>",
        "",
        '#define SITE_PAGE_ETAG "\\"' + etag + '\\""',
        "",
        "static const uint32_t site_page_gz_len = " + gz.length + ";",
        "",
        "static const uint8_t site_page_gz[] PROGMEM = {",
        ...rows,
        "};",
        "",
    ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const html = bundle();
    const raw = Buffer.from(html, "utf8");
    const gz = gzip(raw);
    mkdirSync(join(here, "dist"), { recursive: true });
    writeFileSync(join(here, "dist", "site.html"), raw);
    writeFileSync(join(here, "..", "firmware", "src", "site_page.h"), header(gz));
    const kb = (n) => (n / 1024).toFixed(1) + " KB";
    console.log("dist/site.html " + raw.length + " bytes (" + kb(raw.length) + "), gzip " + gz.length + " bytes (" + kb(gz.length) + ") of " + kb(LIMIT));
    console.log("firmware/src/site_page.h written");
    if (gz.length > LIMIT) {
        console.error("the gzipped page is over 64 KB");
        process.exit(1);
    }
}
